// Annual totals from the same daily record used by the spiral. No API calls.

export function aggregateYears(days, today) {
  const years = new Map();
  const currentYear = Number(today.slice(0, 4));
  for (const day of days) {
    if (day.date > today) continue;
    const year = Number(day.date.slice(0, 4));
    const row = years.get(year) ?? {
      year,
      contributions: 0,
      activeDays: 0,
      partial: year === currentYear && today !== `${year}-12-31`,
    };
    row.contributions += day.count;
    if (day.count > 0) row.activeDays += 1;
    years.set(year, row);
  }
  return [...years.values()].sort((a, b) => b.year - a.year);
}

export function renderArchive(days, today, theme) {
  const rows = aggregateYears(days, today);
  const width = 640, height = rows.length ? 88 + rows.length * 28 : 128;
  const total = rows.reduce((sum, row) => sum + row.contributions, 0);
  const active = rows.reduce((sum, row) => sum + row.activeDays, 0);
  const format = (number) => number.toLocaleString('en-US');
  const description = [
    `Annual record through ${today}: ${format(total)} contributions across ${format(active)} active days.`,
    'An active day has at least one contribution. An asterisk marks a partial year.',
    ...rows.map((row) => `${row.year}: ${format(row.contributions)} contributions, ${format(row.activeDays)} active days${row.partial ? `, through ${today}` : ''}.`),
  ].join(' ');
  const body = rows.map((row, index) => {
    const y = 86 + index * 28;
    return `<g>
<text x="24" y="${y}" class="${row.partial ? 'current' : 'year'}">${row.year}${row.partial ? '*' : ''}</text>
<text x="398" y="${y}" text-anchor="end" class="value">${format(row.contributions)}</text>
<text x="616" y="${y}" text-anchor="end" class="value">${format(row.activeDays)}</text>
</g>`;
  }).join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="archive-title archive-desc">
<title id="archive-title">Annual contribution record through ${escape(today)}</title>
<desc id="archive-desc">${escape(description)}</desc>
<!-- generated by scripts/archive.mjs, do not edit -->
<style>
text{font:16px ui-monospace,SFMono-Regular,"SF Mono",Menlo,Consolas,"Liberation Mono",monospace;letter-spacing:.03em;fill:${theme.note}}
.heading{font-size:18px}.value,.year,.current{font-size:24px;letter-spacing:0;fill:${theme.strong}}
.current{fill:${theme.signal}}.rule{stroke:${theme.line};stroke-opacity:.18}
</style>
<text x="24" y="24" class="heading">ANNUAL RECORD</text>
<text x="616" y="24" text-anchor="end" class="heading">THROUGH ${escape(today)}</text>
<text x="24" y="56">YEAR</text>
<text x="398" y="56" text-anchor="end">CONTRIBUTIONS</text>
<text x="616" y="56" text-anchor="end">ACTIVE DAYS</text>
<path d="M24 65H616" class="rule"/>
${body || '<text x="24" y="100" class="heading">No contribution data.</text>'}
<path d="M24 ${height - 16}H616" class="rule"/>
</svg>
`;
}

function escape(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;',
  })[character]);
}
